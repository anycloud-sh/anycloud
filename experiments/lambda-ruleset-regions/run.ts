#!/usr/bin/env tsx
/**
 * Which Lambda regions accept a per-instance firewall ruleset.
 *
 * `run` creates one empty ruleset per catalog region, records the outcome, and
 * deletes it again. `cleanup` deletes every ruleset carrying this experiment's
 * name prefix and fails unless none remain. Nothing else is created: no
 * instances, keys, or rules. Reports go to SPIKE_OUTPUT_DIR as
 * lambda-ruleset-<phase>.json.
 */
import { randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { LambdaCatalogFetcher } from '../../src/shared/catalog/lambda.js';

const API = 'https://cloud.lambda.ai/api/v1';
const NAME_PREFIX = 'anycloud-spike-ruleset-';
const REQUEST_INTERVAL_MS = 1_100;
const TIMEOUT_MS = 30_000;

interface Ruleset {
  id: string;
  name: string;
  region: { name: string };
}

interface InstanceTypes {
  [name: string]: {
    instance_type: {
      architecture?: string;
      gpu_description?: string;
      specs?: { gpus?: number };
    };
  };
}

class LambdaApiError extends Error {
  constructor(
    readonly status: number,
    message: string,
  ) {
    super(message);
  }
}

let nextRequestAt = 0;

async function api<T>(
  apiKey: string,
  method: string,
  path: string,
  body?: unknown,
): Promise<T> {
  const waitMs = nextRequestAt - Date.now();
  if (waitMs > 0) await delay(waitMs);
  nextRequestAt = Date.now() + REQUEST_INTERVAL_MS;
  const response = await fetch(`${API}${path}`, {
    method,
    headers: {
      Authorization: `Basic ${Buffer.from(`${apiKey}:`).toString('base64')}`,
      'Content-Type': 'application/json',
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  const json = (await response.json().catch(() => undefined)) as
    | { data?: T; error?: { code?: string; message?: string } }
    | undefined;
  if (!response.ok || json?.error) {
    const error = json?.error;
    throw new LambdaApiError(
      response.status,
      `${method} ${path}: HTTP ${response.status} [${error?.code ?? 'unknown'}] ${error?.message ?? ''}`.trim(),
    );
  }
  return json?.data as T;
}

function report(phase: string, value: unknown): void {
  const dir = process.env.SPIKE_OUTPUT_DIR ?? '.';
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, `lambda-ruleset-${phase}.json`),
    `${JSON.stringify(value, null, 2)}\n`,
  );
}

async function deleteOwnedRulesets(apiKey: string): Promise<{
  deleted: string[];
  remaining: string[];
}> {
  const deleted: string[] = [];
  const owned = (
    await api<Ruleset[]>(apiKey, 'GET', '/firewall-rulesets')
  ).filter((ruleset) => ruleset.name.startsWith(NAME_PREFIX));
  for (const ruleset of owned) {
    try {
      await api(apiKey, 'DELETE', `/firewall-rulesets/${ruleset.id}`);
      deleted.push(ruleset.id);
    } catch (error) {
      if (!(error instanceof LambdaApiError && error.status === 404))
        throw error;
    }
  }
  const remaining = (await api<Ruleset[]>(apiKey, 'GET', '/firewall-rulesets'))
    .filter((ruleset) => ruleset.name.startsWith(NAME_PREFIX))
    .map((ruleset) => `${ruleset.id} ${ruleset.name}`);
  return { deleted, remaining };
}

async function run(apiKey: string): Promise<void> {
  const runId = randomBytes(4).toString('hex');
  // The published catalog is generated by this fetcher, so its rows are
  // exactly the instance types x regions AnyCloud admits for Lambda.
  const catalog = await new LambdaCatalogFetcher({ apiKey }).fetchAll();
  const regions = [...new Set(catalog.map((row) => row.region))].sort();
  const instanceTypes = await api<InstanceTypes>(
    apiKey,
    'GET',
    '/instance-types',
  );

  const results: Array<{
    region: string;
    supported: boolean;
    error?: string;
    deleted?: boolean;
  }> = [];
  for (const region of regions) {
    const name = `${NAME_PREFIX}${runId}-${region}`;
    try {
      const ruleset = await api<Ruleset>(apiKey, 'POST', '/firewall-rulesets', {
        name,
        region,
        rules: [],
      });
      let deleted = false;
      try {
        await api(apiKey, 'DELETE', `/firewall-rulesets/${ruleset.id}`);
        deleted = true;
      } catch (error) {
        console.error(`delete ${ruleset.id} failed: ${String(error)}`);
      }
      results.push({ region, supported: true, deleted });
    } catch (error) {
      results.push({
        region,
        supported: false,
        error: error instanceof Error ? error.message : String(error),
      });
    }
    console.log(JSON.stringify(results.at(-1)));
  }

  const unsupported = new Set(
    results.filter((r) => !r.supported).map((r) => r.region),
  );
  const rows = (filter: (region: string) => boolean) =>
    catalog.filter((row) => filter(row.region));
  const summarize = (subset: typeof catalog) => ({
    instanceTypeRegions: subset.length,
    instanceTypes: [...new Set(subset.map((row) => row.instanceType))].sort(),
    gpuTypes: [
      ...new Set(
        subset.flatMap((row) =>
          row.acceleratorName ? [row.acceleratorName] : [],
        ),
      ),
    ].sort(),
  });
  const architectures = Object.fromEntries(
    Object.entries(instanceTypes).map(([name, entry]) => [
      name,
      entry.instance_type.architecture ?? 'unknown',
    ]),
  );

  const summary = {
    runId,
    namePrefix: `${NAME_PREFIX}${runId}-`,
    regions,
    supported: results.filter((r) => r.supported).map((r) => r.region),
    unsupported: [...unsupported],
    results,
    catalog: {
      all: summarize(catalog),
      unsupportedRegions: summarize(rows((region) => unsupported.has(region))),
      unsupportedOnly: summarize(
        catalog.filter(
          (row) =>
            unsupported.has(row.region) &&
            !catalog.some(
              (other) =>
                other.instanceType === row.instanceType &&
                !unsupported.has(other.region),
            ),
        ),
      ),
    },
    architectures,
  };
  report('run', summary);
  console.log(JSON.stringify(summary.catalog, null, 2));
  if (results.some((r) => r.supported && !r.deleted)) {
    throw new Error('a probe ruleset was not deleted; cleanup will retry');
  }
}

async function main(): Promise<void> {
  const apiKey = process.env.LAMBDA_API_KEY;
  if (!apiKey) throw new Error('LAMBDA_API_KEY is required');
  const phase = process.argv[2] ?? process.env.SPIKE_PHASE ?? 'run';
  if (phase === 'run') {
    await run(apiKey);
  } else if (phase === 'cleanup') {
    const result = await deleteOwnedRulesets(apiKey);
    report('cleanup', result);
    console.log(JSON.stringify(result));
    if (result.remaining.length > 0) {
      throw new Error(`rulesets remain: ${result.remaining.join(', ')}`);
    }
  } else {
    throw new Error(`unknown phase ${phase}`);
  }
}

main().then(
  () => process.exit(0),
  (error: unknown) => {
    console.error(error);
    process.exit(1);
  },
);
