import { describe, expect, test } from 'vitest';

import {
  FetchFailureCapture,
  fetchFailureProbes,
} from '../integration/e2e/internal/substrates/cloud-cluster/hosted-fetch-failure.js';
import { commandResultForTest } from './helpers/e2e.js';

const URL = 'https://e2e-clust-1.anycloud.sh';

const reached = commandResultForTest({ stdout: '{}' });
const refused = commandResultForTest({
  exitCode: 1,
  combined: '✗ Request failed with status 503',
});
const fetchFailed = commandResultForTest({
  exitCode: 1,
  combined: '✗ fetch failed',
});

function capture() {
  const runs: { executable: string; args: readonly string[]; label: string }[] =
    [];
  const capture = new FetchFailureCapture(
    {
      run: async (executable, args, options) => {
        runs.push({ executable, args, label: options?.label ?? '' });
        return commandResultForTest();
      },
    },
    () => URL,
  );
  const labels = () =>
    runs.map((run) => /^hosted-fetch-failed-\d+/u.exec(run.label)?.[0]);
  return { capture, runs, labels };
}

describe('hosted fetch failed capture', () => {
  test('probes the runner resolver, DNS over HTTPS, the edge and dig at both resolvers', () => {
    const dig = (server: string[], type: string) => [
      'dig',
      ...server,
      'e2e-clust-1.anycloud.sh',
      type,
      '+noall',
      '+comments',
      '+answer',
      '+authority',
      '+stats',
      '+tries=1',
      '+time=5',
    ];
    const resolvConf =
      '# Generated by Docker\nsearch ec2.internal\nnameserver 172.31.0.2\nnameserver 10.0.0.2\n';
    expect(fetchFailureProbes(`${URL}/v1/version`, resolvConf)).toEqual([
      ['getent', ['getent', 'hosts', 'e2e-clust-1.anycloud.sh']],
      [
        'doh',
        [
          'curl',
          '-sv',
          '--max-time',
          '20',
          '-H',
          'accept: application/dns-json',
          'https://1.1.1.1/dns-query?name=e2e-clust-1.anycloud.sh&type=A',
        ],
      ],
      [
        'edge',
        [
          'curl',
          '-sv',
          '--max-time',
          '20',
          'https://e2e-clust-1.anycloud.sh/v1/version',
        ],
      ],
      ['dig-vpc-A', dig(['@172.31.0.2'], 'A')],
      ['dig-public-A', dig(['@1.1.1.1'], 'A')],
      ['dig-vpc-AAAA', dig(['@172.31.0.2'], 'AAAA')],
      ['dig-public-AAAA', dig(['@1.1.1.1'], 'AAAA')],
    ]);
    // No nameserver: dig falls back to its own default resolver.
    expect(fetchFailureProbes(URL, '').at(3)).toEqual([
      'dig-vpc-A',
      dig([], 'A'),
    ]);
  });

  test('records once per outage onset; only a successful call ends the outage', async () => {
    const { capture: c, runs, labels } = capture();
    for (const result of [
      reached,
      refused,
      fetchFailed,
      fetchFailed,
      refused,
      fetchFailed,
      reached,
      fetchFailed,
    ]) {
      c.observe(result);
    }
    await c.settled();
    // Each onset reads resolv.conf first, so onset 2's probes may run first.
    expect(labels().sort()).toEqual(
      ['1', '2'].flatMap((onset) =>
        Array<string>(7).fill(`hosted-fetch-failed-${onset}`),
      ),
    );
    expect(
      runs
        .filter((run) => run.label.startsWith('hosted-fetch-failed-1-'))
        .map((run) => run.executable),
    ).toEqual(['getent', 'curl', 'curl', ...Array<string>(4).fill('dig')]);
  });

  test("a Bun-compiled release CLI's connect failure is a fetch failure", async () => {
    const { capture: c, labels } = capture();
    c.observe(
      commandResultForTest({
        exitCode: 1,
        combined:
          'error: Unable to connect. Is the computer able to access the url?',
      }),
    );
    await c.settled();
    expect(labels()).toEqual(Array<string>(7).fill('hosted-fetch-failed-1'));
  });

  test('never throws when the probes or the cluster record fail', async () => {
    const failing = new FetchFailureCapture(
      {
        run: async () => {
          throw new Error('runner down');
        },
      },
      () => {
        throw new Error('Cluster is not created');
      },
    );
    failing.observe(fetchFailed);
    await expect(failing.settled()).resolves.toBeUndefined();
    const probesDown = new FetchFailureCapture(
      {
        run: async () => {
          throw new Error('runner down');
        },
      },
      () => URL,
    );
    probesDown.observe(fetchFailed);
    await expect(probesDown.settled()).resolves.toBeUndefined();
  });
});
